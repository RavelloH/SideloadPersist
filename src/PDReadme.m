void PDReadmeUpdate(NSArray<NSString *> *verifiedScopes) {
    NSString *root=PDStorageRoot();
    NSString *readme=[root stringByAppendingPathComponent:@"README.md"];
    NSString *marker=[root stringByAppendingPathComponent:@".readme-generated.sha256"];
    NSFileManager *fm=NSFileManager.defaultManager;
    BOOL present=[fm fileExistsAtPath:readme];
    NSString *previousHash=[[NSString stringWithContentsOfFile:marker
        encoding:NSUTF8StringEncoding error:nil]
        stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceAndNewlineCharacterSet];
    NSData *old=present ? [NSData dataWithContentsOfFile:readme] : nil;
    if(present && (!previousHash.length || ![PDReadmeHash(old) isEqualToString:previousHash])) {
        PDStorageTrace(@"README was manually created or changed; preserving user contents");
        return;
    }
    NSString *content=PDReadmeText(verifiedScopes ?: @[]);
    NSData *fresh=[content dataUsingEncoding:NSUTF8StringEncoding];
    if(!fresh || [old isEqualToData:fresh]) return;
    NSError *error=nil;
    if([fresh writeToFile:readme options:NSDataWritingAtomic error:&error]) {
        NSString *sha=PDReadmeHash(fresh);
        if(![sha writeToFile:marker atomically:YES encoding:NSUTF8StringEncoding error:&error])
            PDStorageTrace(@"Unable to write README generated hash: %@",error);
        PDStorageTrace(@"README.md generated with %lu mapped scopes",(unsigned long)verifiedScopes.count);
    } else {
        PDStorageTrace(@"Unable to write SideloadPersist/README.md: %@",error);
    }
}
