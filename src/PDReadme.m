#import "PDReadme.h"
#import "PDStorage.h"
#import <CommonCrypto/CommonDigest.h>

static NSString *PDReadmeHash(NSData *bytes) {
    if(!bytes) return nil;
    unsigned char sha[CC_SHA256_DIGEST_LENGTH]={0};
    CC_SHA256(bytes.bytes,(CC_LONG)bytes.length,sha);
    NSMutableString *hex=[NSMutableString string];
    for(NSUInteger i=0;i<sizeof(sha);i++) [hex appendFormat:@"%02x",sha[i]];
    return hex;
}
static NSString *PDReadmeDisplayName(void) {
    NSDictionary *info=NSBundle.mainBundle.infoDictionary;
    return info[@"CFBundleDisplayName"] ?: info[@"CFBundleName"] ?: @"当前应用";
}
